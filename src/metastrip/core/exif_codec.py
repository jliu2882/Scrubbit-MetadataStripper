"""Reading and selectively rewriting EXIF blobs (shared by all formats)."""

from __future__ import annotations

from typing import Any

import piexif

from metastrip.core.errors import CorruptFileError
from metastrip.core.models import RawEntry

#: piexif IFD key -> (group label shown to the user, piexif.TAGS table)
IFD_GROUPS: dict[str, tuple[str, str]] = {
    "0th": ("Image", "Image"),
    "Exif": ("Exif", "Exif"),
    "GPS": ("GPS", "GPS"),
    "Interop": ("Interop", "Interop"),
}

THUMBNAIL_ID = "Thumbnail.Embedded Image"
_POINTER_TAGS = {34665, 34853, 40965}  # regenerated by piexif.dump
_RATIONAL_TYPES = {5, 10}
_MAX_LIST_ITEMS = 64


def load(blob: bytes) -> dict[str, Any]:
    """Parse an EXIF blob (with or without the ``Exif\\0\\0`` prefix)."""
    try:
        return piexif.load(blob)
    except Exception as exc:  # piexif raises many unrelated types
        raise CorruptFileError(f"Unreadable EXIF data: {exc}") from exc


def _tag_info(table: str, tag: int) -> tuple[str, int | None]:
    info = piexif.TAGS[table].get(tag)
    if info is None:
        return f"Tag0x{tag:04X}", None
    return info["name"], info["type"]


def _format_rational(pair: tuple[int, int]) -> str:
    num, den = pair
    if den == 0:
        return f"{num}/0"
    if num % den == 0:
        return str(num // den)
    return f"{num / den:.6g}"


def format_value(value: Any, type_id: int | None = None) -> str:
    """Render any EXIF value as short, human-readable text."""
    if isinstance(value, bytes):
        if value[:8] in (b"ASCII\x00\x00\x00", b"UNICODE\x00", b"JIS\x00\x00\x00\x00\x00"):
            value = value[8:]
        text = value.rstrip(b"\x00")
        try:
            decoded = text.decode("utf-8")
        except UnicodeDecodeError:
            return f"<{len(value)} bytes>"
        if decoded.isprintable():
            return decoded
        return f"<{len(value)} bytes>"
    if isinstance(value, tuple):
        if type_id in _RATIONAL_TYPES:
            if len(value) == 2 and all(isinstance(v, int) for v in value):
                return _format_rational(value)  # type: ignore[arg-type]
            parts = [_format_rational(v) for v in value[:_MAX_LIST_ITEMS] if isinstance(v, tuple)]
            return ", ".join(parts)
        return ", ".join(str(v) for v in value[:_MAX_LIST_ITEMS])
    return str(value)


def entries(exif: dict[str, Any]) -> list[RawEntry]:
    """Flatten a parsed EXIF dict into user-facing entries."""
    result: list[RawEntry] = []
    for ifd, (group, table) in IFD_GROUPS.items():
        for tag, value in sorted(exif.get(ifd, {}).items()):
            if tag in _POINTER_TAGS:
                continue
            name, type_id = _tag_info(table, tag)
            result.append(RawEntry(group, name, format_value(value, type_id)))
    thumb = exif.get("thumbnail")
    if thumb:
        result.append(RawEntry("Thumbnail", "Embedded Image", f"<{len(thumb)} bytes>"))
    return result


def get_orientation(exif: dict[str, Any]) -> int:
    value = exif.get("0th", {}).get(piexif.ImageIFD.Orientation, 1)
    return value if isinstance(value, int) else 1


def filter_exif(
    exif: dict[str, Any],
    remove_ids: frozenset[str] | None,
    keep_orientation: bool = True,
) -> bytes | None:
    """Return a new EXIF blob without ``remove_ids`` (``None`` removes all).

    The result starts with ``Exif\\0\\0``. ``None`` is returned when nothing
    would be left to write.
    """
    out: dict[str, Any] = {"0th": {}, "Exif": {}, "GPS": {}, "Interop": {}, "1st": {}, "thumbnail": None}

    if remove_ids is None:
        orientation = get_orientation(exif)
        if keep_orientation and orientation not in (0, 1):
            out["0th"][piexif.ImageIFD.Orientation] = orientation
    else:
        for ifd, (group, table) in IFD_GROUPS.items():
            for tag, value in exif.get(ifd, {}).items():
                if tag in _POINTER_TAGS:
                    continue
                name, _ = _tag_info(table, tag)
                if f"{group}.{name}" not in remove_ids:
                    out[ifd][tag] = value
        if exif.get("thumbnail") and THUMBNAIL_ID not in remove_ids:
            out["1st"] = exif.get("1st", {})
            out["thumbnail"] = exif["thumbnail"]

    if not any(out[k] for k in ("0th", "Exif", "GPS", "Interop")) and not out["thumbnail"]:
        return None
    try:
        return piexif.dump(out)
    except Exception as exc:
        raise CorruptFileError(f"Could not re-encode EXIF data: {exc}") from exc
